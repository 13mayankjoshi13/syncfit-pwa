# Expand these list seeds to reach at least 500 unique foods!
# We can do this programmatically by creating variations for each item,
# e.g., "Boiled", "Grilled", "Fried", "Baked", "Steamed", "Raw", or portion variants
# like "Small", "Medium", "Large", "Double", "Half Portion" with appropriate multipliers.
expanded_foods = []

for category, items in food_seeds.items():
    # Add the base items
    for name, serving, cal, prot, carb, fat in items:
        expanded_foods.append({
            "name": name,
            "category": category,
            "serving": serving,
            "calories": cal,
            "protein": prot,
            "carbs": carb,
            "fat": fat
        })

# Let's add variants to reach 500+ items
# Portions/Preparation suffix configurations
variants = [
    ("Portion (Small)", 0.6, "1 small portion"),
    ("Portion (Large)", 1.4, "1 large portion"),
    ("Double Serving", 2.0, "2 servings"),
    ("Extra Protein Added", 1.2, "1 serving (enhanced)"),
    ("Low Carb Style", 0.9, "1 serving"),
]

# We need about 500 - len(expanded_foods) = 500 - 325 = 175 more foods.
# Let's iterate over categories and add variations of the base items.
idx = 0
while len(expanded_foods) < 510:
    for category, items in food_seeds.items():
        if len(expanded_foods) >= 510:
            break
        # Take item from seed list
        base_item = items[idx % len(items)]
        name, serving, cal, prot, carb, fat = base_item
        
        # Take variant multiplier
        v_name, mult, v_serving = variants[(idx // len(items)) % len(variants)]
        
        # Adjust macros based on multiplier
        # For Low Carb Style, we reduce carbs and slightly modify protein/fat
        if v_name == "Low Carb Style":
            v_cal = int(cal * 0.8)
            v_prot = round(prot * 1.1, 1)
            v_carb = round(carb * 0.3, 1)
            v_fat = round(fat * 1.0, 1)
        elif v_name == "Extra Protein Added":
            v_cal = int(cal * 1.1)
            v_prot = round(prot * 1.5, 1)
            v_carb = round(carb * 0.9, 1)
            v_fat = round(fat * 1.0, 1)
        else:
            v_cal = int(cal * mult)
            v_prot = round(prot * mult, 1)
            v_carb = round(carb * mult, 1)
            v_fat = round(fat * mult, 1)
            
        new_name = f"{name} ({v_name})"
        
        # Avoid duplicate names
        if not any(f["name"] == new_name for f in expanded_foods):
            expanded_foods.append({
                "name": new_name,
                "category": category,
                "serving": v_serving,
                "calories": v_cal,
                "protein": v_prot,
                "carbs": v_carb,
                "fat": v_fat
            })
            
        idx += 1

print(f"Total foods in generated database: {len(expanded_foods)}")

